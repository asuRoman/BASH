#!/bin/bash

# Скрипт находит URL с наибольшим числом запросов
# в логе веб-сервера — только за период с момента прошлого запуска.
# При первом запуске обрабатывает весь лог.
# Использует: find, sed (выбор новых строк), awk/sort/uniq (подсчёт), trap (уборка).

LOG_NAME="access-4560-644067.log"      # имя файла лога
STATE="/tmp/${LOG_NAME}.urls.last"     # файл состояния: номер последней обработанной строки
TMP="$(mktemp)"                        # временный файл — сюда попадут только новые строки

LOCK="/tmp/$(basename "$0").lock"        # файл блокировки паралельного запуска по имени скрипта
exec 9>"$LOCK"                           # открываем fd 9 на запись
flock -n 9 || { echo "Скрипт уже запущен"; exit 1; }

trap 'rm -f "$TMP"' EXIT               # удаляем временный файл при любом завершении

# функция поиска лога
find_log() {
    find /home/asur -maxdepth 1 -type f -name "$LOG_NAME" | head -n 1
}

# функция: выбирает новые строки и печатает топ-10 URL
top_urls() {
    local log="$1"
    local total last

    # общее число строк в файле
    total=$(wc -l < "$log")

    # номер последней обработанной строки (0 при первом запуске)
    last=$(cat "$STATE" 2>/dev/null || echo 0)

    # вырезаем из лога только новые строки
    sed -n "$((last + 1)),${total}p" "$log" > "$TMP"

    # подсчёт URL по вырезанным строкам
    awk '{print $7}' "$TMP" | sort | uniq -c | sort -rn | head -n 10

    # запоминаем текущее общее число строк — отметка для следующего запуска
    echo "$total" > "$STATE"
}

LOG="$(find_log)"
top_urls "$LOG"
