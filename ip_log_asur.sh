#!/bin/bash

# Скрипт находит IP-адреса с наибольшим числом запросов
# в логе веб-сервера — только за период с момента прошлого запуска.
# При первом запуске обрабатывает весь лог.
# Использует: find, sed (выбор новых строк), awk/sort/uniq (подсчёт), trap (уборка).

LOG_NAME="access-4560-644067.log" #объявляем переменную файла лога
STATE="/tmp/${LOG_NAME}.last" # файл состояния хранит номер последней уже обработанной строки лога
TMP="$(mktemp)" # уникальный временный файл в который будут вписаны только новоые строки лога

LOCK="/tmp/$(basename "$0").lock"        # файл блокировки паралельного запуска по имени скрипта
exec 9>"$LOCK"                           # открываем fd 9 на запись
flock -n 9 || { echo "Скрипт уже запущен"; exit 1; }

trap 'rm -f "$TMP"' EXIT # удаляет временный файл при любом завершении

# функция поиска лога
find_log() {
    find /home/asur -maxdepth 1 -type f -name "$LOG_NAME" | head -n 1
}

# выбираем новые строки и печатаем топ 10 IP
top_ips() {
    local log="$1"
    local total last
# считаем общее число строк в файле
	total=$(wc -l < "$log")
# читаем номер последней обработанной строки из файла состояния
	last=$(cat "$STATE" 2>/dev/null || echo 0)
# вырезаем из лога только новые строки
    sed -n "$((last + 1)),${total}p" "$log" > "$TMP"
# подсчёт IP по вырезанным строкам
    awk '{print $1}' "$TMP" | sort | uniq -c | sort -rn | head -n 10
# запоминаем текущее общее число строк
    echo "$total" > "$STATE"
}

LOG="$(find_log)"
top_ips "$LOG"
